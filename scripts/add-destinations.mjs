/**
 * Fetch, optimize and register images for NEW destinations.
 *
 * Run: node scripts/add-destinations.mjs
 *
 * Why this exists instead of just re-running scripts/to-webp.mjs: that script
 * rebuilds data/blur.ts from scratch by walking public/ for .jpg/.png. The
 * original JPEGs were deleted once converted, so re-running it now would emit a
 * blur map containing only whatever new JPEGs happen to be sitting there and
 * silently drop the other 68 entries. This script MERGES instead.
 *
 * Sources images from Wikimedia Commons under free licences only (CC0 / public
 * domain / CC-BY, never NC), matching the existing pipeline. Prints credit lines
 * to paste into CREDITS.md.
 */
import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const DEST_DIR = path.join(ROOT, "public", "destinations");
const BLUR_FILE = path.join(ROOT, "data", "blur.ts");
const UA = "MrAdventureTravelSite/1.0 (https://mradventure.lk; hyshamhashim@gmail.com)";
const API = "https://commons.wikimedia.org/w/api.php";

const strip = (s) => (s || "").replace(/<[^>]*>/g, "").replace(/\s+/g, " ").trim();
const okLicense = (l) => /cc0|public domain|pdm|cc-by(?!-nc)|cc by(?! nc)/i.test(l || "");

async function search(query) {
  const params = new URLSearchParams({
    action: "query",
    generator: "search",
    gsrsearch: `filetype:bitmap ${query}`,
    gsrnamespace: "6",
    gsrlimit: "30",
    prop: "imageinfo",
    iiprop: "url|size|mime|extmetadata",
    iiurlwidth: "1400",
    format: "json",
  });
  const r = await fetch(`${API}?${params}`, { headers: { "User-Agent": UA } });
  const j = await r.json();
  return Object.values(j.query?.pages || {})
    .map((p) => p.imageinfo?.[0])
    .filter(Boolean)
    .filter((i) => /image\/(jpeg|png)/.test(i.mime))
    // Landscape-ish and big enough to crop into a hero without softening.
    .filter((i) => i.width >= 1400 && i.width > i.height * 1.15 && i.width < i.height * 2.4)
    .map((i) => ({
      thumb: i.thumburl,
      w: i.width,
      h: i.height,
      license: strip(i.extmetadata?.LicenseShortName?.value),
      artist: strip(i.extmetadata?.Artist?.value),
      page: i.descriptionurl,
    }))
    .filter((i) => okLicense(i.license))
    .sort((a, b) => b.w * b.h - a.w * a.h);
}

const targets = [
  { slug: "negombo", queries: ["Negombo lagoon fishing boats Sri Lanka", "Negombo beach Sri Lanka", "Negombo Sri Lanka"] },
  { slug: "mirissa", queries: ["Mirissa beach Sri Lanka", "Mirissa Sri Lanka", "Mirissa harbour Sri Lanka"] },
  { slug: "bentota", queries: ["Bentota beach Sri Lanka", "Bentota river Sri Lanka", "Bentota Sri Lanka"] },
  { slug: "hikkaduwa", queries: ["Hikkaduwa beach Sri Lanka", "Hikkaduwa Sri Lanka", "Hikkaduwa coral reef"] },
  { slug: "nuwara-eliya", queries: ["Nuwara Eliya tea plantation Sri Lanka", "Gregory Lake Nuwara Eliya", "Nuwara Eliya Sri Lanka"] },
  { slug: "yala", queries: ["Yala National Park Sri Lanka", "Yala National Park elephant", "Yala National Park leopard"] },
];

// Load and preserve the existing blur map.
const existing = fs.readFileSync(BLUR_FILE, "utf8");
const jsonStart = existing.indexOf("{");
const jsonEnd = existing.lastIndexOf("}");
const blur = JSON.parse(existing.slice(jsonStart, jsonEnd + 1));
const before = Object.keys(blur).length;
console.log(`Existing blur entries: ${before}`);

const credits = [];
for (const t of targets) {
  let picked = null;
  let usedQuery = "";
  for (const q of t.queries) {
    try {
      const res = await search(q);
      if (res.length) {
        picked = res[0];
        usedQuery = q;
        break;
      }
    } catch (e) {
      console.log(`  ! ${t.slug} "${q}": ${e.message}`);
    }
  }
  if (!picked) {
    console.log(`  ✗ ${t.slug}: no freely-licensed match found`);
    continue;
  }

  const img = await fetch(picked.thumb, { headers: { "User-Agent": UA } });
  const buf = Buffer.from(await img.arrayBuffer());
  const out = path.join(DEST_DIR, `${t.slug}.webp`);

  // Cap at 1400px wide to match the existing destination images and keep the
  // page weight sane — these render into cards well under 400px.
  await sharp(buf).rotate().resize({ width: 1400, withoutEnlargement: true }).webp({ quality: 78, effort: 5 }).toFile(out);

  const tiny = await sharp(buf).rotate().resize({ width: 16 }).webp({ quality: 40 }).toBuffer();
  blur[`/destinations/${t.slug}.webp`] = `data:image/webp;base64,${tiny.toString("base64")}`;

  const kb = Math.round(fs.statSync(out).size / 1024);
  console.log(`  ✓ ${t.slug.padEnd(13)} ${picked.w}x${picked.h} → ${kb}KB  [${picked.license}]  (${usedQuery})`);
  credits.push(`| \`public/destinations/${t.slug}.webp\` | ${t.slug} · ${picked.artist || "unknown"} · ${picked.license} | ${picked.page} |`);
}

const body =
  "// AUTO-GENERATED by scripts/to-webp.mjs — do not edit by hand.\n" +
  "// Maps a /public webp path to a tiny base64 blur placeholder for next/image.\n" +
  "export const blur: Record<string, string> = " +
  JSON.stringify(blur, null, 2) +
  ";\n";
fs.writeFileSync(BLUR_FILE, body);

console.log(`\nBlur entries: ${before} → ${Object.keys(blur).length}`);
console.log("\nAdd to CREDITS.md:\n" + credits.join("\n"));
