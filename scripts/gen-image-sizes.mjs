/**
 * Pre-generate responsive width variants for every photo in public/.
 *
 * Run: node scripts/gen-image-sizes.mjs   (after scripts/to-webp.mjs)
 *
 * WHY THIS EXISTS
 * `output: "export"` has no server, so next/image can't resize on request. The
 * site ran with `images.unoptimized`, which meant zero srcset and every photo
 * shipping at full resolution — measured at 6.94 MB of images on the home page,
 * with 1400px files rendered into 390px cards.
 *
 * The repo already had a Cloudflare loader for this, but it only works once the
 * site sits behind Cloudflare; on any other host every image 404s. Generating
 * the variants at build time instead works on any static host, GitHub Pages
 * included, at the cost of some disk in public/ (only the width the browser
 * actually picks is ever downloaded).
 *
 * Emits `<name>-<width>.webp` beside each source, and data/image-sizes.ts
 * mapping each image to the widths that exist for it. lib/static-image-loader.ts
 * reads that map to resolve a request for width N to the nearest variant.
 */
import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const PUBLIC = path.join(ROOT, "public");

// Mirrors `images.deviceSizes` in next.config.ts — Next only ever asks the
// loader for widths in that list, so generating others would be dead weight.
const LADDER = [320, 480, 640, 828, 1080, 1400, 1920];

// Already-generated variants, so re-runs don't cascade.
const IS_VARIANT = /-\d+\.webp$/i;

function walk(dir) {
  const out = [];
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) out.push(...walk(full));
    else if (/\.webp$/i.test(name) && !IS_VARIANT.test(name)) out.push(full);
  }
  return out;
}

const files = walk(PUBLIC);
const manifest = {};
let written = 0;
let skipped = 0;
let bytes = 0;

for (const src of files) {
  const meta = await sharp(src).metadata();
  const publicPath = "/" + path.relative(PUBLIC, src).split(path.sep).join("/");

  // Never upscale — a 400px logo gets no 1920px variant.
  const widths = LADDER.filter((w) => w <= meta.width);
  if (widths.length === 0) {
    // Smaller than the narrowest rung; serve the original as-is.
    skipped++;
    continue;
  }

  for (const w of widths) {
    const dest = src.replace(/\.webp$/i, `-${w}.webp`);
    if (fs.existsSync(dest) && fs.statSync(dest).mtimeMs >= fs.statSync(src).mtimeMs) {
      bytes += fs.statSync(dest).size;
      continue; // up to date
    }
    await sharp(src).resize({ width: w, withoutEnlargement: true }).webp({ quality: 76, effort: 5 }).toFile(dest);
    bytes += fs.statSync(dest).size;
    written++;
  }

  manifest[publicPath] = widths;
  console.log(`  ✓ ${publicPath}  ${meta.width}px → ${widths.join(", ")}`);
}

const out =
  "// AUTO-GENERATED by scripts/gen-image-sizes.mjs — do not edit by hand.\n" +
  "// Maps a /public webp path to the responsive widths generated for it.\n" +
  "// lib/static-image-loader.ts resolves next/image width requests against this.\n" +
  "export const imageSizes: Record<string, number[]> = " +
  JSON.stringify(manifest, null, 2) +
  ";\n";
fs.writeFileSync(path.join(ROOT, "data", "image-sizes.ts"), out);

console.log(
  `\nDone: ${written} variants written, ${Object.keys(manifest).length} images mapped, ` +
    `${skipped} too small to resize.`,
);
console.log(`Variant payload on disk: ${(bytes / 1024 / 1024).toFixed(2)} MB (only one width is ever fetched).`);
